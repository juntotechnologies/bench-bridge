/** Renders SPEC.md, the human and agent readable form of the spec, from the sources alone. */
import type { Components, Layout, Principles, Spec, Tokens, Viewports } from "./schema"

const BANNER = "<!-- Generated by design/build.ts from the JSON files in this directory. Never edit by hand. -->"
const INTRO = "The design spec: one source for the look of every screen. Copy this directory to a new project to reuse it."

function table(head: string[], rows: string[][]): string[] {
  const divider = head.map(dash)
  return [head, divider, ...rows].map(row)
}

function dash(): string {
  return "---"
}

function row(cells: string[]): string {
  return `| ${cells.join(" | ")} |`
}

function code(text: string): string {
  return `\`${text}\``
}

function tokenSection([group, tokens]: [string, Tokens[string]]): string[] {
  const rows = Object.entries(tokens).map(tokenRow)
  return [`### ${group}`, "", ...table(["Token", "Value", "Use"], rows), ""]
}

function tokenRow([name, token]: [string, Tokens[string][string]]): string[] {
  const note = token.package ? ` Package: ${token.package}.` : ""
  return [code(`--${name}`), code(token.value), `${token.use}.${note}`]
}

function layoutRows(layout: Layout): string[][] {
  return Object.entries(layout).map(layoutRow)
}

function layoutRow([name, measure]: [string, Layout[string]]): string[] {
  return [code(name), String(measure.value), `${measure.use}.`]
}

function viewportRow(viewport: Viewports[number]): string[] {
  return [viewport.name, `${viewport.width} x ${viewport.height}`]
}

function codeList(items: string[]): string {
  return items.length ? items.map(code).join(", ") : "none"
}

function componentRow(component: Components[number]): string[] {
  const { name, selector, use, states, tokens, origin } = component
  return [name, code(selector), `${use}.`, codeList(states), codeList(tokens), origin]
}

function principleLine(principle: Principles[number], index: number): string {
  return `${index + 1}. ${principle.rule} Why: ${principle.why}`
}

export function specMarkdown(spec: Spec): string {
  const lines = [
    BANNER, "", "# Design spec", "", INTRO, "",
    "## Principles", "", ...spec.principles.map(principleLine), "",
    "## Tokens", "", ...Object.entries(spec.tokens).flatMap(tokenSection),
    "## Layout", "", ...table(["Name", "Value", "Use"], layoutRows(spec.layout)), "",
    "## Window sizes", "", "The fit check opens each size.", "", ...table(["Name", "Size"], spec.viewports.map(viewportRow)), "",
    "## Components", "", ...table(["Name", "Selector", "Use", "States", "Tokens", "Origin"], spec.components.map(componentRow)), "",
  ]
  return `${lines.join("\n")}\n`
}
