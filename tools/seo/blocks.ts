/** Generated blocks inside client/index.html: marker pairs, and the one function that fills a block. */

export interface Markers {
  start: string
  end: string
}

export const HEAD_MARKERS: Markers = {
  start: "<!-- seo:head:start (generated by npm run seo from site/seo.json; do not edit) -->",
  end: "<!-- seo:head:end -->",
}

export const BODY_MARKERS: Markers = {
  start: "<!-- seo:body:start (generated by npm run seo from site/seo.json; do not edit) -->",
  end: "<!-- seo:body:end -->",
}

const INDENT = "\n    "

function splitLines(text: string): string[] {
  return text.split("\n")
}

/** Replaces everything from the start marker to the end marker with the given elements, one indent deep. */
export function fillBlock(html: string, markers: Markers, elements: string[]): string {
  const start = html.indexOf(markers.start)
  const end = html.indexOf(markers.end)
  if (start === -1 || end < start) throw new Error(`index.html must hold ${markers.start} and ${markers.end}`)
  const block = [markers.start, ...elements.flatMap(splitLines), markers.end].join(INDENT)
  return html.slice(0, start) + block + html.slice(end + markers.end.length)
}
