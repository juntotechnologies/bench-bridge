/** Names of the generated discovery files, the note that heads each one, and absolute and root-relative URLs. */
import type { Site } from "./site"

export const GENERATED_NOTE = "Generated by npm run seo from site/seo.json. Do not edit."

export const FILE_NAMES = {
  robots: "robots.txt",
  sitemap: "sitemap.xml",
  llms: "llms.txt",
  agentsTxt: "agents.txt",
  agentsJson: ".well-known/agents.json",
} as const

export function absoluteUrl(site: Site, path: string): string {
  return new URL(path, site.url).toString()
}

/** The path a page uses to reach a public file, so the link works under the Vite base. */
export function publicHref(site: Site, file: string): string {
  return new URL(file, site.url).pathname
}
